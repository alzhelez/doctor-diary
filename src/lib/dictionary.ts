/**
 * Словари для разбора надиктованных фраз.
 *
 * Регулярки работают по нормализованному тексту: нижний регистр, «ё» → «е».
 * \b в JS не понимает кириллицу, поэтому границы слов задаются явно через
 * (?:^|[^а-яa-z]) — без lookbehind, чтобы работало и на старых iPhone.
 */

/** Начало слова: начало строки или не-буква. */
const B = '(?:^|[^а-яa-z])';
/** Конец слова. */
const E = '(?=$|[^а-яa-z])';

